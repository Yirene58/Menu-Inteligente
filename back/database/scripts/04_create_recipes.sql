CREATE TABLE IF NOT EXISTS recetas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL UNIQUE,
    descripcion VARCHAR(500),
    categoria VARCHAR(80) NOT NULL DEFAULT 'Plato principal',
    minutos SMALLINT NOT NULL CHECK (minutos > 0),
    imagen_url VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS receta_ingredientes (
    receta_id BIGINT NOT NULL REFERENCES recetas(id) ON DELETE CASCADE,
    nombre VARCHAR(120) NOT NULL,
    cantidad DECIMAL(12, 3) NOT NULL CHECK (cantidad > 0),
    unidad VARCHAR(40) NOT NULL DEFAULT 'unidad',
    PRIMARY KEY (receta_id, nombre)
);

CREATE INDEX IF NOT EXISTS idx_receta_ingredientes_nombre
    ON receta_ingredientes (nombre);

