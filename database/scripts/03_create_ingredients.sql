-- Inventory persistence for the storage and recipe suggestions feature.
CREATE TABLE IF NOT EXISTS ingredientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    nombre VARCHAR(120) NOT NULL,
    cantidad DECIMAL(12, 3) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    unidad VARCHAR(40),
    fecha_vencimiento DATE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ingredientes_usuario_vencimiento
    ON ingredientes (usuario_id, fecha_vencimiento);
